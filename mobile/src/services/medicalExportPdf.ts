const bidi = bidiFactory();

const reverseChars = (text: string): string => text.split('').reverse().join('');

/** Base direction of a paragraph: the first strong character decides (UAX #9
 * P2/P3). 1 = right-to-left. */
function paragraphLevel(text: string): 0 | 1 {
  const {paragraphs} = bidi.getEmbeddingLevels(text);
  return paragraphs[0]?.level === 1 ? 1 : 0;
}

/** A string whose glyphs, once fontkit has laid it out (joining forms applied,
 * glyph order reversed for right-to-left text), read in the requested visual
 * direction. fontkit picks the direction from the script of the string itself:
 * for the normal case — Arabic letters drawn right-to-left — the logical string
 * is already right. It is only pre-arranged when the verified outcome differs
 * (e.g. Arabic-Indic digits, which are numbers: left-to-right inside Arabic
 * text). Both candidates are checked against fontkit; nothing is guessed. */
export function arrangeForArabicFace(
  text: string,
  wantRtl: boolean,
  probe: FontkitFont,
): string {
  const visual = wantRtl ? reverseChars(text) : text;
  const outcome = (candidate: string): string =>
    probe.layout(candidate).direction === 'rtl' ? reverseChars(candidate) : candidate;
  if (outcome(text) === visual) {return text;}
  const reversed = reverseChars(text);
  if (outcome(reversed) === visual) {return reversed;}
  return visual;
}

/** fontkit's Indic shaper gives the left vowel sign (e, ai, o, au) its word-INITIAL form whenever the character before its syllable is not a
 * format character or a nonspacing mark, so the second syllable of ভালো or জেনে is drawn as if it opened a word. HarfBuzz (and so every
 * Android text view) applies the initial form only when the previous character is not a letter or a mark. A format character in front of
 * every syllable start that follows another Bengali character tells fontkit exactly that, and breaks nothing inside a conjunct (a virama
 * keeps the letter it joins, so none is put after one). A ZWNJ does it, except after anusvara / visarga / candrabindu (U+0981-0983): there
 * fontkit moves the ZWNJ in front of the sign, so a ZWJ (which stays in logical order) is used. Either shapes to an empty zero-advance
 * glyph. Verified word by word against HarfBuzz (docs/i18n/bengali-pdf-font.md). */
export function guardBengaliSyllables(text: string): string {
  const chars = Array.from(text);
  let out = '';
  chars.forEach((char, index) => {
    const cp = char.codePointAt(0) as number;
    const previous = chars[index - 1];
    const startsSyllable = (cp >= 0x0985 && cp <= 0x09b9) || cp === 0x09ce || cp === 0x09dc || cp === 0x09dd || cp === 0x09df;
    if (startsSyllable && previous && /[ঁ-৿]/.test(previous) && previous !== '্' && previous !== '‌' && previous !== '‍') {
      out += /[ঁ-ঃ]/.test(previous) ? '‍' : '‌';
    }
    out += char;
  });
  return out;
}

/** A Bengali fontkit face that shapes like HarfBuzz: fontkit's OpenType gaps fixed for this face only (fontkitOpenTypeFixes.ts) and every layout
 * going through guardBengaliSyllables, so measuring and drawing agree. */
export function createBengaliFace(base64: string): ShapingFont {
  const face = fontkit.create(decodeFromBase64(base64)) as unknown as FixableFont & ShapingFont;
  applyFontkitOpenTypeFixes(face);
  return {unitsPerEm: face.unitsPerEm, layout: (text: string) => face.layout(guardBengaliSyllables(text)) as ShapedGlyphRun};
}

type SinhalaFontkit = {
  unitsPerEm: number;
  layout: (text: string) => {glyphs: Array<{id: number}>; positions: ShapedGlyphRun['positions']};
  glyphForCodePoint: (codePoint: number) => {id: number; advanceWidth: number};
};

/** A Sinhala fontkit face. fontkit's universal shaper (the one it uses for Sinhala) throws on a few clusters (a two-part vowel sign such as ේ ෝ
 * when its syllable is not followed by a letter), so every layout goes word by word: the word as is; if that throws, the word followed by a
 * letter (dropped again afterwards); if that throws too, the glyphs of the letters unshaped. The face has no U+25CC on purpose: fontkit then
 * does not insert a dotted circle into a cluster it considers broken. Measured against HarfBuzz on every distinct Sinhala word of the app
 * (2,529: dictionary, 73 articles, 41 pregnancy weeks) 2,515 are glyph-for-glyph identical, 10 differ in where a prebase vowel sign sits in a
 * conjunct with a rakaransaya / yansaya, and 4 use the unshaped fallback. */
export function createSinhalaFace(base64: string): ShapingFont {
  const face = fontkit.create(decodeFromBase64(base64)) as unknown as SinhalaFontkit;
  const shapeWord = (word: string): ShapedGlyphRun => {
    const keep = (run: {glyphs: Array<{id: number}>; positions: ShapedGlyphRun['positions']}, drop: number): ShapedGlyphRun => ({
      glyphs: run.glyphs.slice(0, run.glyphs.length - drop).map(glyph => ({id: glyph.id})),
      positions: run.positions.slice(0, run.positions.length - drop),
    });
    try {
      return keep(face.layout(word), 0);
    } catch {
      // fall through to the next attempt
    }
    try {
      return keep(face.layout(`${word}ක`), 1);
    } catch {
      // fall through to the unshaped letters
    }
    const glyphs: Array<{id: number}> = [];
    const positions: ShapedGlyphRun['positions'] = [];
    Array.from(word).forEach(char => {
      const glyph = face.glyphForCodePoint(char.codePointAt(0) as number);
      glyphs.push({id: glyph.id});
      positions.push({xAdvance: glyph.advanceWidth, yAdvance: 0, xOffset: 0, yOffset: 0});
    });
    return {glyphs, positions};
  };
  return {
    unitsPerEm: face.unitsPerEm,
    layout: (text: string) => {
      const run: ShapedGlyphRun = {glyphs: [], positions: []};
      text.split(/( +)/).forEach(part => {
        if (!part) {return;}
        const piece = part.startsWith(' ') ? face.layout(part) : shapeWord(part);
        run.glyphs.push(...piece.glyphs.map(glyph => ({id: glyph.id})));
        run.positions.push(...piece.positions);
      });
      return run;
    },
  };
}

/** HarfBuzz splits SARA AM (U+0E33) into NIKHAHIT (U+0E4D) + SARA AA (U+0E32) and puts a tone mark typed before it after the nikhahit; fontkit's default shaper
 * does neither, which leaves the tone mark at the wrong height. Doing it on the text first makes fontkit's output identical to HarfBuzz's (verified word by word
 * on every Thai word of the app: 4,719 distinct words, 115 of them differed without this step, none with it). */
export function guardThaiSaraAm(text: string): string {
  return text.replace(/([่-๋])ำ/g, 'ํ$1า').replace(/ำ/g, 'ํา');
}

/** A Thai fontkit face that shapes like HarfBuzz (see guardThaiSaraAm); every layout goes through it so measuring and drawing agree. */
export function createThaiFace(base64: string): ShapingFont {
  const face = fontkit.create(decodeFromBase64(base64)) as unknown as ShapingFont;
  return {unitsPerEm: face.unitsPerEm, layout: (text: string) => face.layout(guardThaiSaraAm(text)) as ShapedGlyphRun};
}

type DrawRun = {text: string; font: PDFFont};

const wordAdvances = new WeakMap<ShapingFont, Map<string, number>>();

/** Advance of one space-free piece of text in font units, shaped once and remembered: the line breaker measures every growing
 * candidate line, and re-shaping a whole line for each added word (fontkit's Indic shaper is slow) would be quadratic. */
function pieceAdvance(face: ShapingFont, piece: string): number {
  let cache = wordAdvances.get(face);
  if (!cache) {
    cache = new Map<string, number>();
    wordAdvances.set(face, cache);
  }
  let advance = cache.get(piece);
  if (advance === undefined) {
    advance = face.layout(piece).positions.reduce((sum, position) => sum + position.xAdvance, 0);
    cache.set(piece, advance);
  }
  return advance;
}

/** Width of a shaped run in points: the glyph advances fontkit computed, summed word by word. Shaping never crosses a space
 * (a space ends the syllable) and the face has no kerning against it, so the sum equals the advance of the whole run
 * (a test pins that against the real font). */
export function shapedWidth(face: ShapingFont, text: string, size: number): number {
  let units = 0;
  text.split(' ').forEach((piece, index) => {
    if (index > 0) {units += pieceAdvance(face, ' ');}
    if (piece) {units += pieceAdvance(face, piece);}
  });
  return (units * size) / face.unitsPerEm;
}

/** Indic line (Hindi / Bengali): left-to-right runs, each on the face that can draw it. The letters, signs and joiners of a script are drawn with
 * that script's Noto Sans face; Latin letters, the bullet and degree signs (not in the Devanagari face) with Helvetica; a stretch of characters BOTH a
 * face and Helvetica have (spaces, digits, punctuation) follows the Indic text it comes after, so a sentence stays one shaped run. Never splits inside a
 * syllable: only characters of the script go to its face. A character only an Indic face has (₹, danda, double danda) always goes to it. */
function indicRuns(line: string, allFaces: DevanagariFaces[], latinFont: PDFFont, bold: boolean): DrawRun[] {
  type Kind = number | 'lat' | 'both';
  const kinds: Kind[] = Array.from(line).map(char => {
    const cp = char.codePointAt(0) as number;
    const own = allFaces.findIndex(faces => faces.isScript(cp));
    if (own >= 0) {return own;}
    const holder = allFaces.findIndex(faces => faces.support.has(cp));
    if (holder < 0) {return 'lat';}
    return allFaces[holder].latinSupport.has(cp) ? 'both' : holder;
  });
  let previous: number | 'lat' = 'lat';
  const resolved = kinds.map((kind): number | 'lat' => {
    const value: number | 'lat' = kind === 'both' ? previous : kind;
    previous = value;
    return value;
  });
  const runs: DrawRun[] = [];
  Array.from(line).forEach((char, index) => {
    const which = resolved[index];
    const font = which === 'lat' ? latinFont : bold ? allFaces[which].bold : allFaces[which].regular;
    const last = runs[runs.length - 1];
    if (last && last.font === font) {last.text += char;} else {runs.push({text: char, font});}
  });
  return runs;
}

const needsIndicFace = (line: string, faces: DevanagariFaces): boolean =>
  Array.from(line).some(char => {
    const cp = char.codePointAt(0) as number;
    return faces.isScript(cp) || (faces.support.has(cp) && !faces.latinSupport.has(cp));
  });

/** The runs of one (already wrapped) line, in VISUAL left-to-right order, each
 * with the exact string to hand to pdf-lib and the face to draw it with. */
export function layoutLineRuns(line: string, paraLevel: 0 | 1, fonts: Fonts, bold: boolean): DrawRun[] {
  const latinFont = bold ? fonts.latinBold : fonts.latin;
  // A line takes this path when it holds Devanagari / Bengali OR any character only an Indic face has (a wrapped line that is just
  // '₹500' must not reach Helvetica, which cannot encode the rupee sign).
  const indicFaces = [fonts.bengali, fonts.devanagari, fonts.sinhala, fonts.thai, fonts.georgian, fonts.armenian].filter((faces): faces is DevanagariFaces => Boolean(faces));
  if (indicFaces.length && !containsArabicScript(line) && indicFaces.some(faces => needsIndicFace(line, faces))) {
    return indicRuns(line, indicFaces, latinFont, bold);
  }
  if (!fonts.arabic || !fonts.probe || !containsArabicScript(line)) {
    // No Arabic on this line: plain left-to-right text, exactly as before.
    return line ? [{text: line, font: latinFont}] : [];
  }
  const arabic = fonts.arabic;
  const probe = fonts.probe;
  const {levels} = bidi.getEmbeddingLevels(line, paraLevel === 1 ? 'rtl' : 'ltr');
  const chars = line.split('');

  // 1. Runs of equal embedding level, logical order.
  type LevelRun = {chars: string[]; level: number};
  const levelRuns: LevelRun[] = [];
  chars.forEach((ch, index) => {
    const level = levels[index];
    const last = levelRuns[levelRuns.length - 1];
    if (last && last.level === level) {last.chars.push(ch);} else {levelRuns.push({chars: [ch], level});}
  });

  // 2. Visual order of the runs (UAX #9 rule L2).
  const maxLevel = Math.max(...levelRuns.map(run => run.level));
  const oddLevels = levelRuns.map(run => run.level).filter(level => level % 2 === 1);
  const minOdd = oddLevels.length ? Math.min(...oddLevels) : Infinity;
  const ordered = [...levelRuns];
  for (let level = maxLevel; level >= minOdd; level -= 1) {
    let start = -1;
    for (let index = 0; index <= ordered.length; index += 1) {
      const inScope = index < ordered.length && ordered[index].level >= level;
      if (inScope && start < 0) {start = index;}
      if (!inScope && start >= 0) {
        const reversed = ordered.slice(start, index).reverse();
        ordered.splice(start, index - start, ...reversed);
        start = -1;
      }
    }
  }

  // 3. Each run -> drawable pieces. A piece is drawn with the Arabic face when it
  // is Arabic script (or, inside a right-to-left run, a neutral the Arabic face
  // has); otherwise with Helvetica.
  const pieces: DrawRun[] = [];
  ordered.forEach(run => {
    const rtl = run.level % 2 === 1;
    const source = rtl ? run.chars.map(ch => bidi.getMirroredCharacter(ch) ?? ch) : run.chars;
    type Piece = {chars: string[]; arabic: boolean};
    const logical: Piece[] = [];
    source.forEach(ch => {
      const cp = ch.codePointAt(0) as number;
      // Inside a right-to-left run only Arabic letters and neutrals remain
      // (Latin letters and digits are left-to-right runs of their own).
      // (The list bullet keeps Helvetica's glyph even at the start of an Arabic line.)
      const useArabic = ARABIC_SCRIPT_RE.test(ch) || (rtl && ch !== '•' && fonts.arabicSupport.has(cp));
      const last = logical[logical.length - 1];
      if (last && last.arabic === useArabic) {last.chars.push(ch);} else {logical.push({chars: [ch], arabic: useArabic});}
    });
    const visualPieces = rtl ? [...logical].reverse() : logical;
    visualPieces.forEach(piece => {
      const text = piece.chars.join('');
      if (piece.arabic) {
        pieces.push({text: arrangeForArabicFace(text, rtl, probe), font: arabic});
      } else {
        // Helvetica draws strictly left to right: an RTL run of neutrals is reversed.
        pieces.push({text: rtl ? reverseChars(text) : text, font: latinFont});
      }
    });
  });
  return pieces.filter(piece => piece.text.length > 0);
}

const runWidth = (run: DrawRun, size: number): number => {
  const shaped = shapedFaces.get(run.font);
  return shaped ? shapedWidth(shaped, run.text, size) : run.font.widthOfTextAtSize(run.text, size);
};

const runsWidth = (runs: DrawRun[], size: number): number => runs.reduce((sum, run) => sum + runWidth(run, size), 0);

/** Draws a run of Devanagari glyph by glyph. pdf-lib's own drawText applies the font's substitutions (conjuncts, reph) when it
 * encodes text but throws away the glyph POSITIONS, and Devanagari needs them (vowel signs and nuktas are attached to their
 * base by mark-positioning offsets, not by advance width). So the run is shaped with fontkit and every glyph is placed with
 * its own text matrix. The face is embedded whole, so the glyph ids fontkit returns are the ids in the PDF. */
function drawShapedRun(page: PDFPage, face: ShapingFont, font: PDFFont, text: string, x: number, y: number, size: number, color: ReturnType<typeof rgb>): void {
  const run = face.layout(text);
  const scale = size / face.unitsPerEm;
  const fontKey = page.node.newFontDictionary(font.name, font.ref);
  const operators = [pushGraphicsState(), beginText(), setFillingColor(color), setFontAndSize(fontKey, size)];
  let pen = 0;
  run.glyphs.forEach((glyph, index) => {
    const position = run.positions[index];
    operators.push(
      setTextMatrix(1, 0, 0, 1, x + (pen + position.xOffset) * scale, y + position.yOffset * scale),
      showText(PDFHexString.of(glyph.id.toString(16).padStart(4, '0'))),
    );
    pen += position.xAdvance;
  });
  operators.push(endText(), popGraphicsState());
  page.pushOperators(...operators);
}

/** Kinsoku (line-breaking) rules for Chinese and Japanese: these may not START a line (closing punctuation, ellipsis, dashes, the
 * long-vowel mark, small kana, the katakana middle dot and the iteration marks)... */
const NO_LINE_START = new Set(Array.from('，。、；：？！）”’】》〉』」…—～·％,.;:?!)]}%ー〜・゛゜．ゝゞヽヾ々ぁぃぅぇぉっゃゅょゎァィゥェォッャュョヮヵヶ］｝〕'));
/** ...and these may not END a line (opening brackets and quotes). */
const NO_LINE_END = new Set(Array.from('（“‘【《〈『「([{［｛〔'));

/** The units a too-long token may be broken between: single characters, except in Indic scripts where a base letter keeps its combining marks and a
 * virama (conjunct) keeps the letter it joins, so a break never separates a vowel sign from its consonant. */
const INDIC_TOKEN_RE = /[\u0900-\u097F\u0980-\u09FF]/;
function breakUnits(word: string): string[] {
  const chars = Array.from(word);
  if (!INDIC_TOKEN_RE.test(word)) {return chars;}
  const units: string[] = [];
  chars.forEach((char, index) => {
    const previous = chars[index - 1];
    const joins = units.length > 0 && (/[\p{M}\u200c\u200d]/u.test(char) || previous === '\u094d' || previous === '\u09cd' || previous === '\u200d');
    if (joins) {units[units.length - 1] += char;} else {units.push(char);}
  });
  return units;
}

function wrapText(
  fonts: Fonts,
  text: string,
  size: number,
  bold: boolean,
  maxWidth: number,
  paraLevel: 0 | 1,
): string[] {
  const measure = (candidate: string): number =>
    runsWidth(layoutLineRuns(candidate, paraLevel, fonts, bold), size);
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  words.forEach(word => {
    if (measure(word) > maxWidth) {
      // A single unbreakable token (long URL, pasted code…) wider than the line would
      // run past the right margin and be clipped by the page: break it by character.
      if (current) {lines.push(current);}
      let chunk = '';
      const cjk = containsChinese(word);
      breakUnits(word).forEach(char => {
        if (chunk && measure(`${chunk}${char}`) > maxWidth) {
          // Kinsoku: never leave a closing mark at the start of the next line (carry the previous character with it)
          // and never leave an opening bracket at the end of this one.
          const pieces = Array.from(chunk);
          let carry = '';
          if (cjk && NO_LINE_START.has(char) && pieces.length > 1) {
            carry = pieces.pop() as string;
          }
          while (cjk && pieces.length > 1 && NO_LINE_END.has(pieces[pieces.length - 1])) {
            carry = `${pieces.pop() as string}${carry}`;
          }
          lines.push(pieces.join(''));
          chunk = `${carry}${char}`;
        } else {
          chunk += char;
        }
      });
      current = chunk;
      return;
    }
    const candidate = current ? `${current} ${word}` : word;
    if (measure(candidate) > maxWidth && current) {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  });
  if (current) {lines.push(current);}
  return lines.length ? lines : [''];
}

function newPage(doc: PDFDocument): PDFPage {
  return doc.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
}

function ensureSpace(cursor: Cursor, needed: number): void {
  if (cursor.y - needed < MARGIN) {
    cursor.page = newPage(cursor.doc);
    cursor.y = PAGE_HEIGHT - MARGIN;
  }
}

function drawParagraph(
  cursor: Cursor,
  text: string,
  opts: {size: number; bold?: boolean; color?: ReturnType<typeof rgb>; gapAfter?: number; indent?: number},
): void {
  const {fonts} = cursor;
  const indent = opts.indent ?? 0;
  const maxWidth = PAGE_WIDTH - MARGIN * 2 - indent;
  const clean = sanitizeTextForPdf(text, cursor.support).text;
  const paraLevel: 0 | 1 = fonts.arabic && containsArabicScript(clean) ? paragraphLevel(clean) : 0;
  const lines = wrapText(fonts, clean, opts.size, Boolean(opts.bold), maxWidth, paraLevel);
  lines.forEach(line => {
    ensureSpace(cursor, opts.size * 1.4);
    const runs = layoutLineRuns(line, paraLevel, fonts, Boolean(opts.bold));
    const width = runsWidth(runs, opts.size);
    // A right-to-left paragraph is right-aligned (its indent is taken from the
    // right margin); a left-to-right one keeps the left margin, as before.
    let x = paraLevel === 1 ? PAGE_WIDTH - MARGIN - indent - width : MARGIN + indent;
    runs.forEach(run => {
      const shaped = shapedFaces.get(run.font);
      if (shaped) {
        drawShapedRun(cursor.page, shaped, run.font, run.text, x, cursor.y, opts.size, opts.color ?? TEXT_COLOR);
      } else {
        cursor.page.drawText(run.text, {
          x,
          y: cursor.y,
          size: opts.size,
          font: run.font,
          color: opts.color ?? TEXT_COLOR,
        });
      }
      x += runWidth(run, opts.size);
    });
    cursor.y -= opts.size * 1.4;
  });
  if (opts.gapAfter) {cursor.y -= opts.gapAfter;}
}

function drawRule(cursor: Cursor): void {
  ensureSpace(cursor, 14);
  cursor.page.drawLine({
    start: {x: MARGIN, y: cursor.y},
    end: {x: PAGE_WIDTH - MARGIN, y: cursor.y},
    thickness: 0.75,
    color: RULE_COLOR,
  });
  cursor.y -= 14;
}

/** Renders the full report as a real PDF file's bytes (base64-encoded, ready
 * to be written to disk with @dr.pogodin/react-native-fs's `writeFile(path,
 * base64, 'base64')` — no separate binary/Uint8Array conversion needed).
 * Every line comes straight from the already-filtered, already-selected-only
 * `model` — this function never re-derives, filters, or invents content. */
export async function generateMedicalExportPdfBase64(model: ExportReportModel): Promise<string> {
  const doc = await PDFDocument.create();

  // The embedded Cairo face is only loaded when the report contains Arabic, or one of the six Turkish letters
  // WinAnsi cannot encode. A report without either is generated exactly as before, with the standard fonts.
  const strings = collectModelStrings(model);
  const needsArabic = strings.some(containsArabicScript);
  // A report with Chinese text is drawn entirely with Noto Sans SC (Latin, digits and the Turkish letters included), so
  // no word is split between typefaces; Cyrillic text inside such a report is not drawable by it and is replaced by the
  // standard marker (documented limitation, the CSV export is lossless).
  const needsChinese = strings.some(containsChinese);
  const needsCyrillic = !needsChinese && strings.some(containsCyrillic);
  // A Polish report (ą ć ę ł ń ś ź ż) uses the same embedded DejaVu face: its subset includes Latin Extended-A.
  // A Vietnamese report (ạ ả ấ ơ ư đ …), or an Uzbek one (ʻ ʼ), is drawn entirely with an embedded Noto Sans Regular + Bold subset (pdfVietnameseFont.ts); it takes precedence over the Polish /
  // Romanian test below because ă is shared and the DejaVu subset has no Vietnamese tone letters.
  const needsVietnamese = !needsChinese && !needsCyrillic && strings.some(text => containsVietnameseSpecificLetter(text) || containsUzbekModifierLetter(text) || containsAzerbaijaniSchwa(text));
  const needsPolish = !needsChinese && !needsCyrillic && !needsVietnamese && strings.some(containsPolishSpecificLetter);
  // A Hindi report keeps Helvetica for Latin text and adds Noto Sans Devanagari for the Devanagari runs (the face has no Latin); a Bengali report does the
  // same with Noto Sans Bengali for the Bengali runs.
  const needsDevanagari = strings.some(text => DEVANAGARI_LETTERS_RE.test(text) || (containsDevanagari(text) && !containsBengali(text)));
  // In a Cyrillic or Chinese report the embedded face draws the Turkish letters too, so Cairo is only needed there for
  // Arabic text.
  const needsTurkish = !needsCyrillic && !needsPolish && !needsVietnamese && !needsChinese && strings.some(containsTurkishSpecificLetter);
  let cairo: PDFFont | null = null;
  let probe: FontkitFont | null = null;
  if (needsArabic || needsTurkish) {
    doc.registerFontkit(fontkit);
    cairo = await doc.embedFont(CAIRO_ARABIC_SUBSET_BASE64, {subset: true});
    probe = fontkit.create(decodeFromBase64(CAIRO_ARABIC_SUBSET_BASE64)) as unknown as FontkitFont;
  }
  let dejaVu: PDFFont | null = null;
  let dejaVuBold: PDFFont | null = null;
  if (needsCyrillic || needsPolish) {
    doc.registerFontkit(fontkit);
    dejaVu = await doc.embedFont(DEJAVU_CYRILLIC_REGULAR_SUBSET_BASE64, {subset: true});
    dejaVuBold = await doc.embedFont(DEJAVU_CYRILLIC_BOLD_SUBSET_BASE64, {subset: true});
  } else if (needsVietnamese) {
    // Same slots as the DejaVu face: the Noto Sans subset is the report's single Latin typeface (body, headings, digits), so no word is split between faces.
    doc.registerFontkit(fontkit);
    dejaVu = await doc.embedFont(NOTO_SANS_VIETNAMESE_REGULAR_SUBSET_BASE64, {subset: true});
    dejaVuBold = await doc.embedFont(NOTO_SANS_VIETNAMESE_BOLD_SUBSET_BASE64, {subset: true});
  }
  // CJK text is drawn with Noto Sans JP when the app language is Japanese (Japanese glyph forms, kana, JIS level-1 kanji) and with
  // Noto Sans SC otherwise (Simplified Chinese), exactly as before. `notoSc` / `notoScBold` hold whichever CJK face the report uses.
  const japaneseReport = needsChinese && String(i18n.language ?? '').toLowerCase().startsWith('ja');
  // A Korean app language embeds Noto Sans KR (Hangul syllables, KS X 1001 + every dictionary character) instead.
  const koreanReport = needsChinese && String(i18n.language ?? '').toLowerCase().startsWith('ko');
  let notoSc: PDFFont | null = null;
  let notoScBold: PDFFont | null = null;
  if (needsChinese) {
    doc.registerFontkit(fontkit);
    notoSc = await doc.embedFont(japaneseReport ? NOTO_SANS_JP_REGULAR_SUBSET_BASE64 : koreanReport ? NOTO_SANS_KR_REGULAR_SUBSET_BASE64 : NOTO_SANS_SC_REGULAR_SUBSET_BASE64, {subset: true});
    notoScBold = await doc.embedFont(japaneseReport ? NOTO_SANS_JP_BOLD_SUBSET_BASE64 : koreanReport ? NOTO_SANS_KR_BOLD_SUBSET_BASE64 : NOTO_SANS_SC_BOLD_SUBSET_BASE64, {subset: true});
  }
  let devanagari: DevanagariFaces | null = null;
  if (needsDevanagari) {
    ensureShapingRuntime();
    doc.registerFontkit(fontkit);
    // subset: false — pdf-lib would renumber the glyphs of a subset, and the glyph ids written by drawShapedRun are fontkit's.
    const regular = await doc.embedFont(NOTO_SANS_DEVANAGARI_REGULAR_SUBSET_BASE64, {subset: false});
    const boldFace = await doc.embedFont(NOTO_SANS_DEVANAGARI_BOLD_SUBSET_BASE64, {subset: false});
    shapedFaces.set(regular, fontkit.create(decodeFromBase64(NOTO_SANS_DEVANAGARI_REGULAR_SUBSET_BASE64)) as unknown as ShapingFont);
    shapedFaces.set(boldFace, fontkit.create(decodeFromBase64(NOTO_SANS_DEVANAGARI_BOLD_SUBSET_BASE64)) as unknown as ShapingFont);
    devanagari = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isDevanagariChar};
  }
  const needsBengali = strings.some(containsBengali);
  let bengali: DevanagariFaces | null = null;
  if (needsBengali) {
    ensureShapingRuntime();
    doc.registerFontkit(fontkit);
    const regular = await doc.embedFont(NOTO_SANS_BENGALI_REGULAR_SUBSET_BASE64, {subset: false});
    const boldFace = await doc.embedFont(NOTO_SANS_BENGALI_BOLD_SUBSET_BASE64, {subset: false});
    shapedFaces.set(regular, createBengaliFace(NOTO_SANS_BENGALI_REGULAR_SUBSET_BASE64));
    shapedFaces.set(boldFace, createBengaliFace(NOTO_SANS_BENGALI_BOLD_SUBSET_BASE64));
    bengali = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isBengaliChar};
  }
  const needsSinhala = strings.some(containsSinhala);
  let sinhala: DevanagariFaces | null = null;
  if (needsSinhala) {
    ensureShapingRuntime();
    doc.registerFontkit(fontkit);
    const regular = await doc.embedFont(NOTO_SANS_SINHALA_REGULAR_SUBSET_BASE64, {subset: false});
    const boldFace = await doc.embedFont(NOTO_SANS_SINHALA_BOLD_SUBSET_BASE64, {subset: false});
    shapedFaces.set(regular, createSinhalaFace(NOTO_SANS_SINHALA_REGULAR_SUBSET_BASE64));
    shapedFaces.set(boldFace, createSinhalaFace(NOTO_SANS_SINHALA_BOLD_SUBSET_BASE64));
    sinhala = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isSinhalaChar};
  }
  const needsThai = strings.some(containsThai);
  let thai: DevanagariFaces | null = null;
  if (needsThai) {
    ensureShapingRuntime();
    doc.registerFontkit(fontkit);
    const regular = await doc.embedFont(NOTO_SANS_THAI_REGULAR_SUBSET_BASE64, {subset: false});
    const boldFace = await doc.embedFont(NOTO_SANS_THAI_BOLD_SUBSET_BASE64, {subset: false});
    shapedFaces.set(regular, createThaiFace(NOTO_SANS_THAI_REGULAR_SUBSET_BASE64));
    shapedFaces.set(boldFace, createThaiFace(NOTO_SANS_THAI_BOLD_SUBSET_BASE64));
    thai = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isThaiChar};
  }
  const needsGeorgian = strings.some(containsGeorgian);
  let georgian: DevanagariFaces | null = null;
  if (needsGeorgian) {
    // Georgian (Mkhedruli) has no reordering, conjuncts or combining marks: the faces are NOT registered in shapedFaces, so pdf-lib measures and draws them directly.
    doc.registerFontkit(fontkit);
    const regular = await doc.embedFont(NOTO_SANS_GEORGIAN_REGULAR_SUBSET_BASE64, {subset: true});
    const boldFace = await doc.embedFont(NOTO_SANS_GEORGIAN_BOLD_SUBSET_BASE64, {subset: true});
    georgian = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isGeorgianChar};
  }
  const needsArmenian = strings.some(containsArmenian);
  let armenian: DevanagariFaces | null = null;
  if (needsArmenian) {
    // Armenian has no reordering, conjuncts or combining marks: the faces are NOT registered in shapedFaces, so pdf-lib measures and draws them directly.
    doc.registerFontkit(fontkit);
    const regular = await doc.embedFont(NOTO_SANS_ARMENIAN_REGULAR_SUBSET_BASE64, {subset: true});
    const boldFace = await doc.embedFont(NOTO_SANS_ARMENIAN_BOLD_SUBSET_BASE64, {subset: true});
    armenian = {regular, bold: boldFace, support: pdfCharSupport(regular), latinSupport: new Set<number>(), isScript: isArmenianChar};
  }
  // A Turkish report is drawn entirely with Cairo (Regular for body text, an embedded Cairo Bold subset with the same
  // code points for titles / headings / dates / category labels), so that no word is split between two typefaces and
  // the heading hierarchy survives. Every other report keeps Helvetica / Helvetica-Bold and never embeds the bold face.
  const cairoBold = needsTurkish && cairo ? await doc.embedFont(CAIRO_BOLD_SUBSET_BASE64, {subset: true}) : null;
  const latin = notoSc ?? dejaVu ?? (needsTurkish && cairo ? cairo : await doc.embedFont(StandardFonts.Helvetica));
  const latinBold = notoScBold ?? dejaVuBold ?? cairoBold ?? (await doc.embedFont(StandardFonts.HelveticaBold));
  const arabic: PDFFont | null = needsArabic ? cairo : null;
  const arabicSupport: PdfCharSupport = arabic ? pdfCharSupport(arabic) : new Set<number>();
  if (devanagari) {devanagari.latinSupport = pdfCharSupport(latin);}
  if (bengali) {bengali.latinSupport = pdfCharSupport(latin);}
  if (sinhala) {sinhala.latinSupport = pdfCharSupport(latin);}
  if (thai) {thai.latinSupport = pdfCharSupport(latin);}
  if (georgian) {georgian.latinSupport = pdfCharSupport(latin);}
  if (armenian) {armenian.latinSupport = pdfCharSupport(latin);}
  const fonts: Fonts = {latin, latinBold, arabic, arabicSupport, probe: needsArabic ? probe : null, devanagari, bengali, sinhala, thai, georgian, armenian};
  // Bold shares the regular face's character set, so one check covers both.
  const support: PdfCharSupport = new Set<number>([...pdfCharSupport(latin), ...arabicSupport, ...(devanagari ? devanagari.support : []), ...(bengali ? bengali.support : []), ...(sinhala ? sinhala.support : []), ...(thai ? thai.support : []), ...(georgian ? georgian.support : []), ...(armenian ? armenian.support : [])]);
  const cursor: Cursor = {doc, page: newPage(doc), y: PAGE_HEIGHT - MARGIN, fonts, support};

  drawParagraph(cursor, 'AWA', {size: 22, bold: true, color: TITLE_COLOR, gapAfter: 2});
  drawParagraph(cursor, i18n.t('export.pdf.reportTitle'), {size: 15, bold: true, color: TITLE_COLOR, gapAfter: 10});
  drawParagraph(cursor, `${i18n.t('export.pdf.objectiveLabel')} : ${model.objectiveLabel}`, {size: 10.5, color: MUTED_COLOR});
  drawParagraph(cursor, `${i18n.t('export.pdf.periodLabel')} : ${model.periodLabel}`, {size: 10.5, color: MUTED_COLOR});
  drawParagraph(cursor, `${i18n.t('export.pdf.generatedLabel')} ${model.generatedAtLabel}`, {size: 10.5, color: MUTED_COLOR, gapAfter: 12});

  const hasUnsupportedText = strings.some(value => sanitizeTextForPdf(value, support).replaced);
  const notices = hasUnsupportedText ? [...model.notices, PDF_UNSUPPORTED_NOTICE] : model.notices;

  if (notices.length) {
    notices.forEach(notice => {
      drawParagraph(cursor, notice, {size: 9.5, color: MUTED_COLOR, gapAfter: 2});
    });
    cursor.y -= 4;
  }

  drawRule(cursor);
  cursor.y -= 6;

  ensureSpace(cursor, HEADING_BLOCK); // a heading is never left alone at the bottom of a page
  drawParagraph(cursor, i18n.t('export.pdf.summaryHeading'), {size: 12.5, bold: true, color: TITLE_COLOR, gapAfter: 6});
  drawParagraph(cursor, `${i18n.t('export.pdf.totalDaysLabel')} : ${model.totalDays}`, {size: 10.5, gapAfter: 4});
  if (model.categoryCounts.length) {
    model.categoryCounts.forEach(({label, count}) => {
      drawParagraph(cursor, `${label} : ${i18n.t('export.pdf.daysCount', {count})}`, {size: 10.5, indent: 8});
    });
  }
  cursor.y -= 8;
  drawRule(cursor);
  cursor.y -= 6;

  ensureSpace(cursor, HEADING_BLOCK + DAY_BLOCK);
  drawParagraph(cursor, i18n.t('export.pdf.historyHeading'), {size: 12.5, bold: true, color: TITLE_COLOR, gapAfter: 6});

  if (!model.days.length) {
    drawParagraph(cursor, i18n.t('export.pdf.emptyState'), {
      size: 10.5,
      color: MUTED_COLOR,
    });
  }

  model.days.forEach(day => {
    ensureSpace(cursor, DAY_BLOCK); // date + first category label + its first line stay together
    drawParagraph(cursor, day.dateLabel, {size: 11.5, bold: true, gapAfter: 3});
    day.categories.forEach(category => {
      ensureSpace(cursor, CATEGORY_BLOCK); // label + first bullet never split across pages
      drawParagraph(cursor, category.label, {size: 10, bold: true, indent: 8, gapAfter: 1});
      category.lines.forEach(line => {
        drawParagraph(cursor, `• ${line}`, {size: 10, indent: 16});
      });
      cursor.y -= 2;
    });
    cursor.y -= 6;
  });

  return doc.saveAsBase64();
}
