#!/usr/bin/env node
// Merges da_chunk*.ts files into a single flat da.ts (no imports).
// Run: node scripts/merge-da-chunks.js
'use strict';

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const LOCALES_DIR = path.join(__dirname, '..', 'src', 'i18n', 'locales');

const CHUNKS = [
  'da_chunk1', 'da_chunk2', 'da_chunk3',
  'da_chunk4a', 'da_chunk4b', 'da_chunk4c',
  'da_chunk4d', 'da_chunk4e', 'da_chunk4f',
];

function loadChunk(name) {
  const file = path.join(LOCALES_DIR, `${name}.ts`);
  const src = fs.readFileSync(file, 'utf8');
  const js = ts.transpileModule(src, {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText;
  const mod = {exports: {}};
  // eslint-disable-next-line no-new-func
  new Function('module', 'exports', 'require', js)(mod, mod.exports, () => ({}));
  const keys = Object.keys(mod.exports);
  if (keys.length === 0) throw new Error(`No exports in ${name}`);
  return mod.exports[keys[0]];
}

function serialize(value, indent = 2) {
  const pad = ' '.repeat(indent);
  const padInner = ' '.repeat(indent + 2);
  if (typeof value === 'string') {
    // Use double quotes if the string contains a single quote, otherwise single quotes
    if (value.includes("'")) {
      return JSON.stringify(value); // double-quoted, JSON-escaped
    }
    // Escape backslashes and use single quotes
    return "'" + value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n') + "'";
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map(item => padInner + serialize(item, indent + 2));
    return '[\n' + items.join(',\n') + ',\n' + pad + ']';
  }
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return '{}';
    const lines = entries.map(([k, v]) => {
      const key = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
      return padInner + key + ': ' + serialize(v, indent + 2);
    });
    return '{\n' + lines.join(',\n') + ',\n' + pad + '}';
  }
  return String(value);
}

console.log('Loading chunks...');
const merged = {};
for (const chunk of CHUNKS) {
  try {
    const data = loadChunk(chunk);
    const keys = Object.keys(data);
    console.log(`  ${chunk}: ${keys.length} top-level keys`);
    Object.assign(merged, data);
  } catch (err) {
    console.error(`  ERROR loading ${chunk}: ${err.message}`);
    process.exit(1);
  }
}

console.log(`\nTotal top-level keys: ${Object.keys(merged).length}`);
console.log('Serializing da.ts...');

const header = `// Dansk (da). Generated by scripts/merge-da-chunks.js from parallel translation chunks.
// Do not edit directly — regenerate from chunks or edit the relevant da_chunk*.ts file then re-run.
// Translation: professional, warm, informal "du"; Islamic/medical terms per AWA style guide.
// Key parity: run \`node scripts/check-language-parity.js da\` to verify against en.ts.
`;

const body = `export const da = ${serialize(merged, 0)};\n`;

const output = path.join(LOCALES_DIR, 'da.ts');
fs.writeFileSync(output, header + '\n' + body, 'utf8');
console.log(`Written: ${output} (${Math.round(fs.statSync(output).size / 1024)} KB)`);
